"""`python -m mockmcp eval arithmetic [--check]`: which bench case facts an answer gets by arithmetic (bench/arithmetic.yaml).

Two kinds, both found by running each case's reference calls (classify()):
    stated: false   no reference output states the fact in any spelling (verbatim, the fact's own rounding, k/m/bn scale,
                    a fraction as a %, bench's 0.5% tolerance), so the answer must compute it; derive.derive() says how
                    (sum, mean, difference, ratio, percentage, product, annualise, units) or `unknown`. bench --validate
                    requires every fact in the reference output, so today there are none; the kind is kept for cases
                    whose facts may one day be computed.
    stated: true    an output states it, but it is also the total of other figures on the rows the outputs list (a
                    total over line items, 3+ significant digits, not of a rate column): a model working from the rows
                    adds them up itself.
The file maps case id -> [{fact, op, stated}] for cases with at least one such fact. Running the reference calls needs
the engine, so it is generated here, not in features(): of_task(task) counts the task's required facts
(reference.facts; traps: reference.answerable_facts) listed for its slices' cases. Regenerate after changing
bench/cases or system data, then `eval traps` (the trap bank stores features).
"""
import functools
import re
import tempfile
from datetime import date
from pathlib import Path

import yaml

from .. import bench, db, spec
from . import derive as D

FILE = spec.ROOT / "bench" / "arithmetic.yaml"
HEADER = ("# Generated by `python -m mockmcp eval arithmetic` (mockmcp/eval/arithmetic.py): bench case facts an answer gets by\n"
          "# arithmetic, with how. stated: false = no reference output states it; stated: true = an output states it but it is\n"
          "# also the total of rows the outputs list. Read by features.py (feature `arithmetic`). Do not edit by hand.\n")
OPS = ("sum", "mean", "difference", "ratio", "percentage", "product", "annualise", "units", "unknown")


# ---------- one fact ----------

def _tol(fact: str) -> tuple[float, float] | None:
    """(value, rounding tolerance) of a numeric fact; trailing zeros of an integer are rounding (1,270 -> ±5)."""
    fn = D._fact_num(fact)
    if not fn:
        return None
    f, dp, sig = fn
    if dp:
        return f, 0.5 * 10 ** -dp
    zeros = len(str(int(abs(f)))) - sig
    return f, 0.5 * 10 ** zeros if zeros >= 1 and sig >= 2 else 0.5


def _values(outputs: list[str]) -> list[float]:
    ev = D._evidence(tuple(outputs), ())
    return [n.value for n in ev.nums] + [v for t in outputs for v, _ in bench._numbers(bench._norm(t, table=True))]


def _stated(opt, outputs: list[str], values: list[float]) -> bool:
    """Is one spelling of a fact in the outputs: verbatim, at its rounding, scaled (k/m/bn) or a fraction as a %."""
    text = "\n".join(outputs)
    ft = _tol(str(opt))
    if ft is None:
        return bench._has(opt, text, table=True) or bench._has(opt, text)
    (f, tol), sig = ft, D._fact_num(str(opt))[2]
    for x in values:
        for y, scale in ((x, 1), (x * 100, 100), (x / 1e3, 1e3), (x / 1e6, 1e6), (x / 1e9, 1e9)):
            if scale == 100 and not 0 < abs(x) <= 1.5:
                continue
            if scale >= 1e3 and (abs(x) < scale or sig < 2):
                continue
            if abs(abs(y) - abs(f)) <= tol + 1e-9:
                return True
    return False


def _op(how: str | None) -> str | None:
    """derive()'s description -> op; None for a restatement (rounding, units of the same figure, scale)."""
    if not how:
        return "unknown"
    h = how.lower()
    if h.startswith("restated in other units"):
        return "units"
    if h.startswith("restated"):
        return None
    for key, op in (("column total", "sum"), ("column mean", "mean"), ("annualised", "annualise"), ("sum", "sum"),
                    ("mean", "mean"), ("difference", "difference"), ("ratio", "ratio"), ("percentage", "percentage"),
                    ("product", "product")):
        if h.startswith(key):
            return op
    return "unknown"


NUMTOK = re.compile(r"(?<![\w.])-?\d+(?:\.\d+)?(?![\w.])")
# A stated figure counts only as a total of 3+ significant digits, not of a rate column: on hand checks (70 matches)
# means and short sums matched by chance far more often than not (a 2-row mean lands between neighbours), and so did
# totals of percentage or per-unit columns; other totals were right about nine times in ten.
AGGREGATES = ("sum",)


RATE_COL = re.compile(r"pct|percent|share|rate|ratio|_per_|score", re.I)


def _how(o, outputs: list[str], prompt: str, rows, tol: float | None = None, totals_only: bool = False) -> str | None:
    """The op derive() finds for the figure; totals_only: None unless it is a sum, and not of a rate column (a total of
    percentages or per-unit rates is a chance match)."""
    sentence = re.sub(r"\d[\d,.]*", "", prompt).strip() + f" The answer is {o}."
    try:
        how = D.derive(str(o), sentence, sentence, outputs, rows, tol)
    except Exception:  # noqa: BLE001 - a derivation that trips on odd output is just not found
        return None if totals_only else "unknown"
    op = _op(how)
    if totals_only and (op not in AGGREGATES or RATE_COL.search(how.split(" = ")[0])):
        return None
    return op


def _loose(o) -> float:
    """The tolerance a stated figure of 4+ significant digits is rebuilt to: its rounding plus one unit of its last digit.
    Some tools sum floats in a varying order and print 230 or 230.1, 11233612 or 11233613 from run to run, so an exact
    match on the last digit would make the file flicker."""
    f, dp, sig = D._fact_num(str(o))
    return _tol(str(o))[1] + (10 ** -dp if sig >= 4 else 0)


def _blank(outputs: list[str], spellings: list) -> list[str]:
    """The outputs with every number that states the figure in any of its spellings removed (cells left empty), so
    derive() must build it. All spellings at once, each within its _loose() tolerance, so run-to-run noise in
    the last digit of a tool's total cannot leave it standing."""
    tols = [(_tol(str(o))[0], _loose(o)) for o in spellings]

    def rep(m):
        return "" if any(abs(abs(float(m.group())) - abs(f)) <= tol + 1e-9 for f, tol in tols) else m.group()
    return [NUMTOK.sub(rep, o) for o in outputs]


def classify(fact, outputs: list[str], prompt: str = "", rows: list[dict] | None = None) -> dict | None:
    """How an answer gets a required fact by arithmetic, or None when it reads it off a tool result:
    {op, stated: false}  no output states it (any alternative, any spelling, bench's 0.5% tolerance), so it is computed;
                         op from derive(), `unknown` when derive() cannot rebuild it
    {op, stated: true}   an output states it, but it is also the sum or mean of other figures on the rows the outputs
                         list (a total over line items): a model working from the rows adds them up itself"""
    values = _values(outputs)
    opts = fact if isinstance(fact, list) else [fact]
    nums = [o for o in opts if D._fact_num(str(o))]
    text = "\n".join(outputs)
    if not any(_stated(o, outputs, values) or bench._has(o, text, table=True) or bench._has(o, text) for o in opts):
        if not nums:
            return None    # a name or date no output holds is a case bug (bench --validate), not arithmetic
        ops = [op for o in nums if (op := _how(o, outputs, prompt, rows))]
        if len(ops) < len(nums):
            return None    # a restatement after all (derive found it at another scale or rounding)
        return {"op": next((o for o in ops if o != "unknown"), "unknown"), "stated": False}
    blank = _blank(outputs, nums) if nums else outputs
    for o in nums:
        if abs(_tol(str(o))[0]) < 1e-9 or D._fact_num(str(o))[2] < 3:
            continue
        if op := _how(o, blank, prompt, rows, _loose(o), totals_only=True):
            return {"op": op, "stated": True}
    return None


# ---------- all cases ----------

def case_facts(sid: str, cases: list[dict]) -> dict:
    """{case id: [{fact, op}]} for one system's cases, running each case's ref calls on fresh state."""
    from ..server import Engine
    out = {}
    with tempfile.TemporaryDirectory() as tmp:
        old, db.STATE = db.STATE, Path(tmp)
        try:
            eng, dirty = Engine([sid]), False
            writes = {t.name for t in eng.systems[sid].tools if t.writes}
            names = {t.name for t in eng.systems[sid].tools}
            for c in cases:
                if dirty:
                    db.STATE = Path(tempfile.mkdtemp(dir=tmp))
                    eng, dirty = Engine([sid]), False
                outs, rows = [], []
                for r in c.get("ref") or []:
                    if r["tool"] not in names:
                        continue
                    args = bench._shift_args(r.get("args") or {})
                    text, _ = eng.call(sid, r["tool"], args)
                    dirty = dirty or r["tool"] in writes
                    outs.append(text), rows.append({"args": args})
                facts = list(c.get("facts") or []) + [f for f in c.get("scenario_facts") or [] if f not in (c.get("facts") or [])]
                prompt = " ".join(str(c.get("prompt", "")).split())
                got = [{"fact": f, **how} for f in facts if (how := classify(f, outs, prompt, rows))]
                if got:
                    out[c["id"]] = got
        finally:
            db.STATE = old
    return out


def build(sids: list[str] | None = None) -> dict:
    """{case id: [{fact, op}]} over every bench case (or the named systems), sorted by case id; deterministic for a
    given world week (the world's today is pinned as bench --validate pins it)."""
    real = date.fromisoformat(spec.WORLD["as_of"])
    out = {}
    try:
        spec.set_today(real)
        for f in sorted(bench.CASES.glob("*.yaml")):
            if sids is None or f.stem in sids:
                out.update(case_facts(f.stem, bench.load(f.stem)))
    finally:
        spec.set_today(real)
    return dict(sorted(out.items()))


def dump(data: dict) -> str:
    return HEADER + (yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=140) if data else "{}\n")


@functools.lru_cache(maxsize=1)
def load() -> dict:
    """{case id: {repr(fact): op}} from bench/arithmetic.yaml ({} when the file is absent)."""
    if not FILE.exists():
        return {}
    data = yaml.safe_load(FILE.read_text()) or {}
    return {cid: {repr(e["fact"]): e["op"] for e in facts} for cid, facts in data.items()}


def of_task(task: dict, table: dict | None = None) -> list[str]:
    """Ops of the task's required facts that an answer must compute, one per fact (a fact two slices share counts once)."""
    table = load() if table is None else table
    ref = task.get("reference") or {}
    req = ref.get("answerable_facts") if task.get("trap") and "answerable_facts" in ref else ref.get("facts") or []
    want, ops = {repr(f) for f in req or []}, {}
    for s in ref.get("slices") or []:
        for k, op in (table.get(s.get("case_id")) or {}).items():
            if k in want and k in {repr(f) for f in s.get("facts") or []}:
                ops.setdefault(k, op)
    return [ops[k] for k in sorted(ops)]


def summary(data: dict) -> str:
    from collections import Counter
    facts = [e for v in data.values() for e in v]
    ops = Counter(e["op"] for e in facts)
    return (f"{len(data)} cases with facts got by arithmetic, {len(facts)} facts "
            f"({sum(not e['stated'] for e in facts)} in no output): " + ", ".join(f"{o} {ops[o]}" for o in OPS if ops[o]))


# ---------- CLI ----------

def add_args(p):
    p.add_argument("--out", default=str(FILE), help="output file (default bench/arithmetic.yaml)")
    p.add_argument("--check", action="store_true", help="exit 1 when the file is not what would be generated; write nothing")


def main(a) -> int:
    out = Path(a.out)
    data = build()
    print(summary(data))
    text = dump(data)
    if a.check:
        ok = out.exists() and out.read_text() == text
        print(f"{out} is {'current' if ok else 'STALE: run python -m mockmcp eval arithmetic'}")
        return 0 if ok else 1
    out.write_text(text)
    print(f"wrote {out}")
    return 0

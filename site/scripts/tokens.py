"""Write src/styles/mm-tokens.css: the report palette (mockmcp/eval/svg.py, the source of truth) as --mm-* variables
keyed on Starlight's theme attribute, so the site and the example reports share one set of colours."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from mockmcp.eval.svg import FONT, PALETTE  # noqa: E402


def block(theme: str) -> str:
    return "".join(f"--mm-{k}:{v};" for k, v in PALETTE[theme].items())


out = Path(__file__).resolve().parents[1] / "src/styles/mm-tokens.css"
out.write_text("/* generated by scripts/tokens.py from mockmcp/eval/svg.py; do not edit */\n"
               f":root{{--mm-font:{FONT};{block('light')}}}\n"
               f":root[data-theme='dark']{{{block('dark')}}}\n")
print(f"wrote {out.relative_to(ROOT)}")
